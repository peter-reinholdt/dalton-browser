// Coordinates in application records are always Angstrom; atom ids survive edits.
export const BOHR = 0.529177210903;
export const ELEMENTS =
  'X H He Li Be B C N O F Ne Na Mg Al Si P S Cl Ar K Ca Sc Ti V Cr Mn Fe Co Ni Cu Zn Ga Ge As Se Br Kr Rb Sr Y Zr Nb Mo Tc Ru Rh Pd Ag Cd In Sn Sb Te I Xe Cs Ba La Ce Pr Nd Pm Sm Eu Gd Tb Dy Ho Er Tm Yb Lu Hf Ta W Re Os Ir Pt Au Hg Tl Pb Bi Po At Rn Fr Ra Ac Th Pa U Np Pu Am Cm Bk Cf Es Fm Md No Lr Rf Db Sg Bh Hs Mt Ds Rg Cn Nh Fl Mc Lv Ts Og'.split(
    ' ',
  );
export const atomicNumber = (symbol) => ELEMENTS.indexOf(symbol);
export const uid = () =>
  globalThis.crypto?.randomUUID?.() ??
  `${Date.now().toString(36)}-${Math.random().toString(36).slice(2)}`;
export function molecule(atoms, name = 'Molecule') {
  return {
    id: uid(),
    name,
    atoms: atoms.map((a, i) => ({
      id: a.id ?? `a${i + 1}`,
      symbol: a.symbol,
      x: Number(a.x),
      y: Number(a.y),
      z: Number(a.z),
    })),
    source: 'coordinates',
  };
}
export function parseXYZ(text, name = 'Imported structure', units = 'angstrom') {
  const lines = text.trim().split(/\r?\n/);
  const count = Number(lines[0]);
  if (!Number.isInteger(count) || count < 1 || count > 10000 || lines.length < count + 2)
    throw new Error('XYZ needs an atom count, a comment line, and one coordinate line per atom.');
  const scale = units === 'bohr' ? BOHR : 1;
  const atoms = lines.slice(2, count + 2).map((line) => {
    const [label, ...coords] = line.trim().split(/\s+/);
    const symbol = /^\d+$/.test(label)
      ? ELEMENTS[Number(label)]
      : (label.match(/^([A-Z][a-z]?)(?:[_\d].*)?$/)?.[1] ?? label);
    if (
      atomicNumber(symbol) < 1 ||
      coords.length < 3 ||
      coords.slice(0, 3).some((v) => !Number.isFinite(Number(v)))
    )
      throw new Error(`Invalid XYZ atom: ${line}`);
    return {
      symbol,
      x: Number(coords[0]) * scale,
      y: Number(coords[1]) * scale,
      z: Number(coords[2]) * scale,
    };
  });
  return molecule(atoms, name);
}
export function toXYZ(mol, units = 'angstrom') {
  const scale = units === 'bohr' ? 1 / BOHR : 1;
  return `${mol.atoms.length}\n${mol.name.replace(/[\r\n]/g, ' ')} (${units})\n${mol.atoms.map((a) => `${a.symbol} ${[a.x, a.y, a.z].map((v) => (v * scale).toFixed(9)).join(' ')}`).join('\n')}\n`;
}
export function parseDaltonMolecule(text, name = 'Imported Dalton molecule') {
  const lines = text.split(/\r?\n/);
  if (lines[0]?.trim().toUpperCase() !== 'BASIS')
    throw new Error(
      'Guided import supports BASIS-format Dalton molecules. Use expert mode for other formats.',
    );
  const header = lines.findIndex((line) => /Atomtypes\s*=/i.test(line));
  if (header < 0) throw new Error('Missing Atomtypes in Dalton molecule.');
  const scale = /Angstrom/i.test(lines[header]) ? 1 : BOHR;
  const atoms = [];
  let remaining = 0,
    z = 0;
  for (const line of lines.slice(header + 1)) {
    const group = line.match(/Charge\s*=\s*([\d.]+).*Atoms\s*=\s*(\d+)/i);
    if (group) {
      z = Number(group[1]);
      remaining = Number(group[2]);
      if (!Number.isInteger(z) || !ELEMENTS[z]) throw new Error('Unsupported nuclear charge.');
      continue;
    }
    if (!remaining || !line.trim() || /^\s*[!$]/.test(line)) continue;
    const parts = line.trim().split(/\s+/);
    if (
      parts.length < 4 ||
      parts.slice(1, 4).some((v) => !Number.isFinite(Number(v.replace(/[dD]/, 'e'))))
    )
      throw new Error('Invalid Dalton coordinates.');
    atoms.push({
      symbol: ELEMENTS[z],
      ...Object.fromEntries(
        ['x', 'y', 'z'].map((key, i) => [key, Number(parts[i + 1].replace(/[dD]/, 'e')) * scale]),
      ),
    });
    remaining--;
  }
  if (remaining || !atoms.length) throw new Error('Incomplete Dalton molecule.');
  return {
    ...molecule(atoms, name),
    basis: lines[1].trim(),
    charge: Number(lines[header].match(/\bCharge\s*=\s*([-+]?\d+)/i)?.[1] ?? 0),
  };
}
export function toDaltonMolecule(mol, settings) {
  const groups = new Map();
  for (const atom of mol.atoms) {
    if (!groups.has(atom.symbol)) groups.set(atom.symbol, []);
    groups.get(atom.symbol).push(atom);
  }
  return (
    `BASIS\n${settings.basis}\n${mol.name.replace(/[\r\n]/g, ' ').slice(0, 70)}\nGenerated by Web Dalton\nAtomtypes=${groups.size} Charge=${settings.charge} Angstrom NoSymmetry\n` +
    [...groups]
      .map(
        ([symbol, atoms]) =>
          `Charge=${atomicNumber(symbol)}.0 Atoms=${atoms.length}\n${atoms.map((a, i) => `${symbol}${i + 1} ${a.x.toFixed(10)} ${a.y.toFixed(10)} ${a.z.toFixed(10)}`).join('\n')}\n`,
      )
      .join('')
  );
}
export function validateMolecule(mol, charge = 0, multiplicity = 1) {
  const errors = [],
    warnings = [];
  if (!mol?.atoms?.length) errors.push('Add a molecule first.');
  const atoms = mol?.atoms ?? [];
  if (atoms.some((a) => atomicNumber(a.symbol) < 1 || ![a.x, a.y, a.z].every(Number.isFinite)))
    errors.push('Every atom needs an element and three finite coordinates.');
  if (!Number.isInteger(charge)) errors.push('Charge must be an integer.');
  const electrons = atoms.reduce((n, a) => n + atomicNumber(a.symbol), 0) - charge;
  if (electrons < 1) errors.push('The molecule must have at least one electron.');
  if (
    !Number.isInteger(multiplicity) ||
    multiplicity < 1 ||
    multiplicity > electrons + 1 ||
    (electrons - multiplicity + 1) % 2
  )
    errors.push('Multiplicity is incompatible with the electron count.');
  let clash = false;
  for (let i = 0; i < atoms.length; i++)
    for (let j = 0; j < i; j++)
      if (
        Math.hypot(atoms[i].x - atoms[j].x, atoms[i].y - atoms[j].y, atoms[i].z - atoms[j].z) < 0.35
      )
        clash = true;
  if (clash) errors.push('Some atoms are closer than 0.35 Å. Check the geometry and its units.');
  if (atoms.length > 40)
    warnings.push(
      'This is a large molecule for a serial browser calculation. Try a smaller basis first.',
    );
  if (!atoms.some((a) => a.symbol === 'H') && atoms.some((a) => ['C', 'N', 'O'].includes(a.symbol)))
    warnings.push('No hydrogen atoms found. Coordinate imports do not add missing hydrogens.');
  if (mol?.source === 'generated')
    warnings.push('This is a generated starting geometry, not a quantum-optimized structure.');
  return { errors, warnings, electrons };
}
export function fingerprint(mol, settings) {
  return JSON.stringify({
    atoms: mol.atoms.map(({ symbol, x, y, z }) => [symbol, x, y, z]),
    basis: settings.basis,
    charge: settings.charge,
    multiplicity: settings.multiplicity,
  });
}
export function measurement(atoms) {
  const diff = (a, b) => [a.x - b.x, a.y - b.y, a.z - b.z],
    dot = (a, b) => a.reduce((s, v, i) => s + v * b[i], 0);
  if (atoms.length === 2) return `${Math.hypot(...diff(atoms[0], atoms[1])).toFixed(4)} Å`;
  if (atoms.length === 3) {
    const a = diff(atoms[0], atoms[1]),
      b = diff(atoms[2], atoms[1]);
    const d = Math.hypot(...a) * Math.hypot(...b);
    return d
      ? `${((Math.acos(Math.max(-1, Math.min(1, dot(a, b) / d))) * 180) / Math.PI).toFixed(2)}°`
      : 'Undefined angle';
  }
  return 'Select two atoms for a distance, or three for an angle.';
}
